_CITY = re.compile(
    r"\b(" + "|".join(re.escape(c) for c in sorted(CITY_AIRPORTS, key=len, reverse=True)) + r")\b",
    re.IGNORECASE,
)
_ACCENTS = str.maketrans("ãáàâéèêíóôõúüç", "aaaaeeeiooouuc")


def airport_codes(text: str) -> set[str]:
    """The airport codes of every city the text names ("a flight to Seattle" gives SEA)."""
    plain = text.lower().translate(_ACCENTS)
    return {code for m in _CITY.finditer(plain) for code in CITY_AIRPORTS[m.group(1).lower()]}
